# Stellar type keywords for classification
STELLAR_TYPE_KEYWORDS = {
    'main_sequence': ['main sequence', 'main-sequence', 'ms star', 'dwarf star', 'hydrogen burning'],
    'giant': ['giant', 'evolved', 'red giant', 'subgiant', 'rgb'],
    'supergiant': ['supergiant', 'super-giant'],
    'white_dwarf': ['white dwarf', 'white-dwarf', 'wd'],
    'subdwarf': ['subdwarf', 'sub-dwarf', 'sdss'],
}


def extract_stellar_params_from_text(text: str) -> Dict[str, Optional[float]]:
    """
    Extract Teff, logg, and FeH from generated text.

    Handles spaces in decimals (e.g., "4. 31" -> 4.31)

    Looks for patterns like:
    - "Teff = 5800 K", "Teff=5800K", "temperature of 5800 K"
    - "logg = 4.5", "log g = 4.5", "logg of 4. 31" (with space)
    - "FeH = -0.5", "[Fe/H] = -0. 5", "metallicity of -0.5"

    Args:
        text: Generated text to parse

    Returns:
        Dictionary with 'Teff', 'logg', 'FeH' keys (None if not found)
    """
    result = {'Teff': None, 'logg': None, 'FeH': None}

    if not text:
        return result

    text_lower = text.lower()

    # Define patterns that handle spaces in decimals (e.g., "4. 31")
    patterns = {
        'Teff': [
            r'(?:t_?eff|effective temperature|temperature)\s*(?:\(teff\))?\s*[=:~]?\s*(?:of\s+)?(?:is\s+)?(?:approximately\s+)?(\d+(?:\.\s*\d+)?)\s*k?',
            r'(\d{4,5}(?:\.\s*\d+)?)\s*k',  # Match 4-5 digit numbers followed by K
        ],
        'logg': [
            r'(?:log\s*g|logg|surface gravity)\s*(?:\(logg\))?\s*[=:~]?\s*(?:of\s+)?(?:is\s+)?(?:approximately\s+)?([-+]?\d+(?:\.\s*\d+)?)',
            r'log\s*\(\s*g\s*\)\s*[=:~]?\s*(?:of\s+)?([-+]?\d+(?:\.\s*\d+)?)',
        ],
        'FeH': [
            r'\[\s*fe\s*/\s*h\s*\]\s*[=:~]?\s*(?:of\s+)?(?:is\s+)?([-+]?\d+\.\s*\d+)',  # [Fe/H] with decimal
            r'\[\s*fe\s*/\s*h\s*\]\s*[=:~]?\s*(?:of\s+)?(?:is\s+)?([-+]?\d+)',  # [Fe/H] without decimal
            r'(?:feh|metallicity)\s*(?:\(\[?fe/?h\]?\))?\s*[=:~]?\s*(?:of\s+)?(?:is\s+)?([-+]?\d+\.\s*\d+)',  # With decimal
            r'(?:feh|metallicity)\s*(?:\(\[?fe/?h\]?\))?\s*[=:~]?\s*(?:of\s+)?(?:is\s+)?([-+]?\d+)',  # Without decimal
        ]
    }

    for param, pattern_list in patterns.items():
        for pattern in pattern_list:
            matches = re.findall(pattern, text_lower, re.IGNORECASE)
            if matches:
                try:
                    # Take the first valid match and remove any spaces from decimal
                    raw_match = matches[0] if isinstance(matches[0], str) else matches[0]
                    cleaned_match = raw_match.replace(' ', '')  # Remove spaces: "3. 96" -> "3.96"
                    value = float(cleaned_match)

                    # Sanity check: filter out obviously wrong values
                    if param == 'Teff' and (value < 2000 or value > 50000):
                        continue
                    if param == 'logg' and (value < -1 or value > 6):
                        continue
                    if param == 'FeH' and (value < -5 or value > 1):
                        continue

                    result[param] = value
                    break  # Stop after finding first valid match for this parameter
                except (ValueError, IndexError, AttributeError):
                    continue

    return result


def extract_stellar_type_from_text(text: str) -> Optional[str]:
    """
    Extract stellar type classification from generated text.

    Args:
        text: Generated text to parse

    Returns:
        Stellar type string (e.g., 'main_sequence', 'giant', etc.) or None
    """
    if not text:
        return None

    text_lower = text.lower()

    # Check for each type (order matters - check more specific types first)
    for stellar_type, keywords in STELLAR_TYPE_KEYWORDS.items():
        for keyword in keywords:
            if keyword in text_lower:
                return stellar_type

    return None


def compute_parameter_errors(
    generated_params: Dict[str, Optional[float]],
    true_params: Dict[str, Optional[float]]
) -> Dict[str, Optional[float]]:
    """
    Compute absolute errors between generated and true parameters.

    Args:
        generated_params: Extracted parameters from generated text
        true_params: Ground truth parameters

    Returns:
        Dictionary with absolute errors for each parameter (None if missing)
    """
    errors = {}
    for param in ['Teff', 'logg', 'FeH']:
        gen_val = generated_params.get(param)
        true_val = true_params.get(param)

        if gen_val is not None and true_val is not None:
            errors[param] = abs(gen_val - true_val)
        else:
            errors[param] = None

    return errors


def analyze_generation_results(
    json_path: str,
    output_dir: Optional[str] = None,
    figsize: Tuple[int, int] = (14, 6),
) -> Dict[str, Any]:
    """
    Analyze generation results and create comparison plots.

    Args:
        json_path: Path to JSON file with generation results
        output_dir: Directory to save plots (if None, uses same dir as json_path)
        figsize: Figure size for plots

    Returns:
        Dictionary with analysis statistics
    """
    # Load results
    with open(json_path, 'r') as f:
        all_results = json.load(f)

    print(f"Loaded results for {len(all_results)} experiments")

    # Setup output directory
    if output_dir is None:
        output_dir = Path(json_path).parent
    else:
        output_dir = Path(output_dir)
    output_dir.mkdir(exist_ok=True, parents=True)

    # Extract statistics for each experiment
    experiment_stats = {}

    for exp_result in all_results:
        exp_name = exp_result['experiment_name']
        samples = exp_result['samples']

        print(f"\nProcessing {exp_name}...")
        print(f"  Samples: {len(samples)}")

        # Initialize statistics
        stats = {
            'param_errors': {'Teff': [], 'logg': [], 'FeH': []},
            'param_extraction_rate': {'Teff': 0, 'logg': 0, 'FeH': 0},
            'stellar_type_matches': 0,
            'stellar_type_total': 0,
            'stellar_type_extraction_rate': 0,
            'total_samples': len(samples),
        }

        # Process each sample
        for sample in samples:
            # Get true parameters
            true_params = sample.get('stellar_params', {})

            # Extract parameters from description response
            generated_text = sample.get('description_response', '')
            generated_params = extract_stellar_params_from_text(generated_text)

            # Count extractions (regardless of whether we can compute error)
            for param in ['Teff', 'logg', 'FeH']:
                if generated_params.get(param) is not None:
                    stats['param_extraction_rate'][param] += 1

            # Compute errors (only possible when both values exist)
            errors = compute_parameter_errors(generated_params, true_params)
            for param in ['Teff', 'logg', 'FeH']:
                if errors[param] is not None:
                    stats['param_errors'][param].append(errors[param])

            # Extract stellar type from target and generated text
            target_text = sample.get('target_answer', '')
            true_type = extract_stellar_type_from_text(target_text)
            generated_type = extract_stellar_type_from_text(generated_text)

            if true_type is not None:
                stats['stellar_type_total'] += 1
                if generated_type is not None:
                    stats['stellar_type_extraction_rate'] += 1
                    if generated_type == true_type:
                        stats['stellar_type_matches'] += 1

        # Convert counts to rates
        total = stats['total_samples']
        if total > 0:
            for param in ['Teff', 'logg', 'FeH']:
                stats['param_extraction_rate'][param] /= total
            if stats['stellar_type_total'] > 0:
                stats['stellar_type_extraction_rate'] /= stats['stellar_type_total']

        experiment_stats[exp_name] = stats

        print(f"  Parameter extraction rates:")
        print(f"    Teff: {stats['param_extraction_rate']['Teff']:.2%}")
        print(f"    logg: {stats['param_extraction_rate']['logg']:.2%}")
        print(f"    FeH: {stats['param_extraction_rate']['FeH']:.2%}")
        print(f"  Stellar type accuracy: {stats['stellar_type_matches']}/{stats['stellar_type_total']}")

    # Create plots
    create_comparison_plots(experiment_stats, output_dir, figsize)

    return experiment_stats


def create_comparison_plots(
    experiment_stats: Dict[str, Dict],
    output_dir: Path,
    figsize: Tuple[int, int] = (14, 6),
) -> None:
    """
    Create comparison plots for all experiments.

    Args:
        experiment_stats: Statistics dictionary from analyze_generation_results
        output_dir: Directory to save plots
        figsize: Figure size for plots
    """
    # Set style
    sns.set_style("whitegrid")
    plt.rcParams['font.size'] = 10

    exp_names = list(experiment_stats.keys())

    # Create short labels for experiments
    short_labels = {}
    for name in exp_names:
        # Extract key info from name
        label = name.replace('ablation_s_', '').replace('_', ' ')
        short_labels[name] = label

    # ============================================================================
    # Plot 1: Parameter Extraction Rates
    # ============================================================================
    fig, ax = plt.subplots(figsize=(12, 6))

    params = ['Teff', 'logg', 'FeH']
    x = np.arange(len(exp_names))
    width = 0.25

    for i, param in enumerate(params):
        rates = [experiment_stats[exp]['param_extraction_rate'][param] * 100
                 for exp in exp_names]
        ax.bar(x + i * width, rates, width, label=param, alpha=0.8)

    ax.set_xlabel('Experiment', fontsize=12, fontweight='bold')
    ax.set_ylabel('Extraction Rate (%)', fontsize=12, fontweight='bold')
    ax.set_title('Stellar Parameter Extraction Rates', fontsize=14, fontweight='bold')
    ax.set_xticks(x + width)
    ax.set_xticklabels([short_labels[name] for name in exp_names], rotation=45, ha='right')
    ax.legend()
    ax.grid(True, alpha=0.3, axis='y')

    plt.tight_layout()
    plt.savefig(output_dir / 'parameter_extraction_rates.png', dpi=300, bbox_inches='tight')
    plt.close()
    print(f"Saved: {output_dir / 'parameter_extraction_rates.png'}")

    # ============================================================================
    # Plot 2: Parameter MAE (Mean Absolute Error)
    # ============================================================================
    fig, axes = plt.subplots(1, 3, figsize=figsize)

    for idx, param in enumerate(params):
        ax = axes[idx]

        # Collect MAE for each experiment
        mae_values = []
        labels = []
        colors = []

        for exp_name in exp_names:
            errors = experiment_stats[exp_name]['param_errors'][param]
            if len(errors) > 0:
                mae = np.mean(errors)
                mae_values.append(mae)
                labels.append(short_labels[exp_name])

                # Color by followup training
                if 'fup1' in exp_name:
                    colors.append('steelblue')
                else:
                    colors.append('coral')
            else:
                mae_values.append(0)
                labels.append(short_labels[exp_name])
                colors.append('lightgray')

        # Create bar plot
        bars = ax.bar(range(len(mae_values)), mae_values, color=colors, alpha=0.7, edgecolor='black')

        ax.set_xlabel('Experiment', fontsize=10, fontweight='bold')
        ax.set_ylabel('MAE', fontsize=10, fontweight='bold')
        ax.set_title(f'{param} Prediction Error', fontsize=12, fontweight='bold')
        ax.set_xticks(range(len(labels)))
        ax.set_xticklabels(labels, rotation=45, ha='right', fontsize=8)
        ax.grid(True, alpha=0.3, axis='y')

        # Add value labels on bars
        for bar in bars:
            height = bar.get_height()
            if height > 0:
                ax.text(bar.get_x() + bar.get_width()/2., height,
                       f'{height:.1f}',
                       ha='center', va='bottom', fontsize=8)

    plt.tight_layout()
    plt.savefig(output_dir / 'parameter_mae_comparison.png', dpi=300, bbox_inches='tight')
    plt.close()
    print(f"Saved: {output_dir / 'parameter_mae_comparison.png'}")

    # ============================================================================
    # Plot 3: Stellar Type Prediction Accuracy
    # ============================================================================
    fig, ax = plt.subplots(figsize=(12, 6))

    accuracies = []
    extraction_rates = []
    labels = []
    colors = []

    for exp_name in exp_names:
        stats = experiment_stats[exp_name]

        # Calculate accuracy
        if stats['stellar_type_total'] > 0:
            accuracy = (stats['stellar_type_matches'] / stats['stellar_type_total']) * 100
        else:
            accuracy = 0

        extraction_rate = stats['stellar_type_extraction_rate'] * 100

        accuracies.append(accuracy)
        extraction_rates.append(extraction_rate)
        labels.append(short_labels[exp_name])

        # Color by followup training
        if 'fup1' in exp_name:
            colors.append('steelblue')
        else:
            colors.append('coral')

    x = np.arange(len(exp_names))
    width = 0.35

    bars1 = ax.bar(x - width/2, accuracies, width, label='Accuracy',
                   color=colors, alpha=0.7, edgecolor='black')
    bars2 = ax.bar(x + width/2, extraction_rates, width, label='Extraction Rate',
                   color='lightgreen', alpha=0.7, edgecolor='black')

    ax.set_xlabel('Experiment', fontsize=12, fontweight='bold')
    ax.set_ylabel('Percentage (%)', fontsize=12, fontweight='bold')
    ax.set_title('Stellar Type Prediction Performance', fontsize=14, fontweight='bold')
    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=45, ha='right')
    ax.legend()
    ax.grid(True, alpha=0.3, axis='y')

    # Add value labels on bars
    for bars in [bars1, bars2]:
        for bar in bars:
            height = bar.get_height()
            if height > 0:
                ax.text(bar.get_x() + bar.get_width()/2., height,
                       f'{height:.1f}',
                       ha='center', va='bottom', fontsize=8)

    plt.tight_layout()
    plt.savefig(output_dir / 'stellar_type_accuracy.png', dpi=300, bbox_inches='tight')
    plt.close()
    print(f"Saved: {output_dir / 'stellar_type_accuracy.png'}")

    # ============================================================================
    # Plot 4: Combined Summary Plot
    # ============================================================================
    fig = plt.figure(figsize=(16, 10))
    gs = fig.add_gridspec(2, 3, hspace=0.3, wspace=0.3)

    # Top row: Parameter MAE
    for idx, param in enumerate(params):
        ax = fig.add_subplot(gs[0, idx])

        mae_values = []
        for exp_name in exp_names:
            errors = experiment_stats[exp_name]['param_errors'][param]
            mae = np.mean(errors) if len(errors) > 0 else 0
            mae_values.append(mae)

        colors_param = ['steelblue' if 'fup1' in name else 'coral' for name in exp_names]
        bars = ax.bar(range(len(mae_values)), mae_values, color=colors_param,
                     alpha=0.7, edgecolor='black')

        ax.set_title(f'{param} MAE', fontsize=11, fontweight='bold')
        ax.set_xticks(range(len(exp_names)))
        ax.set_xticklabels([short_labels[n] for n in exp_names],
                          rotation=45, ha='right', fontsize=7)
        ax.grid(True, alpha=0.3, axis='y')

        for bar in bars:
            height = bar.get_height()
            if height > 0:
                ax.text(bar.get_x() + bar.get_width()/2., height,
                       f'{height:.1f}', ha='center', va='bottom', fontsize=7)

    # Bottom left: Stellar type accuracy
    ax = fig.add_subplot(gs[1, 0])
    accuracies = []
    for exp_name in exp_names:
        stats = experiment_stats[exp_name]
        if stats['stellar_type_total'] > 0:
            accuracy = (stats['stellar_type_matches'] / stats['stellar_type_total']) * 100
        else:
            accuracy = 0
        accuracies.append(accuracy)

    colors_type = ['steelblue' if 'fup1' in name else 'coral' for name in exp_names]
    bars = ax.bar(range(len(accuracies)), accuracies, color=colors_type,
                 alpha=0.7, edgecolor='black')
    ax.set_title('Stellar Type Accuracy', fontsize=11, fontweight='bold')
    ax.set_ylabel('Accuracy (%)', fontsize=10)
    ax.set_xticks(range(len(exp_names)))
    ax.set_xticklabels([short_labels[n] for n in exp_names],
                      rotation=45, ha='right', fontsize=7)
    ax.grid(True, alpha=0.3, axis='y')

    for bar in bars:
        height = bar.get_height()
        if height > 0:
            ax.text(bar.get_x() + bar.get_width()/2., height,
                   f'{height:.1f}', ha='center', va='bottom', fontsize=7)

    # Bottom middle: Parameter extraction rates
    ax = fig.add_subplot(gs[1, 1])
    x = np.arange(len(exp_names))
    width = 0.25
    for i, param in enumerate(params):
        rates = [experiment_stats[exp]['param_extraction_rate'][param] * 100
                for exp in exp_names]
        ax.bar(x + i * width, rates, width, label=param, alpha=0.8)
    ax.set_title('Parameter Extraction Rates', fontsize=11, fontweight='bold')
    ax.set_ylabel('Rate (%)', fontsize=10)
    ax.set_xticks(x + width)
    ax.set_xticklabels([short_labels[n] for n in exp_names],
                      rotation=45, ha='right', fontsize=7)
    ax.legend(fontsize=8)
    ax.grid(True, alpha=0.3, axis='y')

    # Bottom right: Summary statistics table
    ax = fig.add_subplot(gs[1, 2])
    ax.axis('tight')
    ax.axis('off')

    # Create summary table
    table_data = []
    table_data.append(['Experiment', 'Avg MAE', 'Type Acc'])

    for exp_name in exp_names:
        stats = experiment_stats[exp_name]

        # Calculate average MAE across all parameters
        all_errors = []
        for param in params:
            all_errors.extend(stats['param_errors'][param])
        avg_mae = np.mean(all_errors) if len(all_errors) > 0 else 0

        # Get type accuracy
        if stats['stellar_type_total'] > 0:
            type_acc = (stats['stellar_type_matches'] / stats['stellar_type_total']) * 100
        else:
            type_acc = 0

        table_data.append([
            short_labels[exp_name][:20],
            f"{avg_mae:.2f}",
            f"{type_acc:.1f}%"
        ])

    table = ax.table(cellText=table_data, cellLoc='left', loc='center',
                    colWidths=[0.5, 0.25, 0.25])
    table.auto_set_font_size(False)
    table.set_fontsize(8)
    table.scale(1, 1.5)

    # Style header row
    for i in range(3):
        table[(0, i)].set_facecolor('#40466e')
        table[(0, i)].set_text_props(weight='bold', color='white')

    # Alternate row colors
    for i in range(1, len(table_data)):
        for j in range(3):
            if i % 2 == 0:
                table[(i, j)].set_facecolor('#f0f0f0')

    ax.set_title('Summary Statistics', fontsize=11, fontweight='bold', pad=20)

    # Add legend for colors
    from matplotlib.patches import Patch
    legend_elements = [
        Patch(facecolor='steelblue', alpha=0.7, label='With Followup'),
        Patch(facecolor='coral', alpha=0.7, label='No Followup')
    ]
    fig.legend(handles=legend_elements, loc='upper right', fontsize=10)

    fig.suptitle('Generation Results Analysis Summary', fontsize=16, fontweight='bold')
    plt.savefig(output_dir / 'summary_combined.png', dpi=300, bbox_inches='tight')
    plt.close()
    print(f"Saved: {output_dir / 'summary_combined.png'}")


def main():
    """Command-line interface"""
    import argparse

    parser = argparse.ArgumentParser(
        description="Analyze generation results from ablation studies"
    )
    parser.add_argument(
        '--json_path',
        type=str,
        required=True,
        help='Path to JSON file with generation results'
    )
    parser.add_argument(
        '--output_dir',
        type=str,
        default=None,
        help='Directory to save plots (default: same as json_path)'
    )
    parser.add_argument(
        '--figsize',
        type=int,
        nargs=2,
        default=[14, 6],
        help='Figure size as width height (default: 14 6)'
    )

    args = parser.parse_args()

    print("="*80)
    print("ANALYZING GENERATION RESULTS")
    print("="*80)
    print(f"Input: {args.json_path}")
    print(f"Output: {args.output_dir or Path(args.json_path).parent}")
    print()

    stats = analyze_generation_results(
        json_path=args.json_path,
        output_dir=args.output_dir,
        figsize=tuple(args.figsize),
    )

    print("\n" + "="*80)
    print("ANALYSIS COMPLETE")
    print("="*80)


if __name__ == '__main__':
    main()
