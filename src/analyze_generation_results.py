"""
Analysis functions for generation comparison results from ablation studies.

This module processes the JSON file generated by compare_followup_responses()
and creates various comparison plots for:
1. Stellar parameter prediction accuracy (Teff, logg, FeH)
2. Stellar type prediction accuracy
"""

